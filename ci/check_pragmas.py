#!/usr/bin/env python3
"""
check_pragmas.py -- L0 guard: no tool directive hides inside an RTL comment
unless it is a named, counted, justified lint waiver.

WHY
  Decision A (docs/results/0028): a line leaves the coverage denominator exactly
  when it leaves synthesis, and the exclusions are GENERATED by
  tools/gen_cov_vlt.py. A hand-written `verilator coverage_off`, or a
  `synthesis translate_off` that makes simulation and silicon differ, would
  bypass that rule from inside a comment, where a diff reader is least likely
  to look. M3.7, docs/results/0030.

WHAT IS SCANNED
  Every .sv/.svh/.v/.vh file under rtl/, whether or not rtl/files.f lists it
  (muldiv.sv is not listed today and carries a waiver). Strings are skipped so
  a "//" inside a literal starts no comment.

WHAT COUNTS AS A DIRECTIVE
  A comment whose first word is one of PREFIXES (case-insensitive), followed by
  another word or by nothing. "// pragma. csr_illegal_o is ..." (rv32_core.sv)
  is prose: the prefix is followed by punctuation. A prose comment that starts
  "// Verilator honours ..." IS flagged -- the scan errs toward loud, and the
  fix is to reword the comment.

  PREFIXES is the set of directive prefixes known to the writer of this script
  (T4/T5, not read from every tool's manual). A vendor prefix missing from it is
  a false negative. Attributes (* ... *) and the `pragma compiler directive are
  NOT comments and are out of scope.

POLICY
  - The only directive allowed is `verilator lint_off NAME` / `lint_on NAME`
    with a single upper-case warning name and nothing else in the comment.
  - Per file and NAME, off/on must alternate, start with off, end with on.
  - Every (file, NAME) seen must be in ci/pragma_allowlist.tsv with the exact
    number of pairs; every allowlist row must be seen (a stale row fails).
  - scope sim_only: every line from lint_off to lint_on must be
    simulation-only by tools/gen_cov_vlt.py's own rule (one rule, not two).

EXIT  0 clean; 1 violation; 2 setup error (nothing scanned, bad allowlist).
"""

import importlib.util
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
ALLOWLIST = REPO / "ci/pragma_allowlist.tsv"
EXTS = {".sv", ".svh", ".v", ".vh"}
PREFIXES = ("verilator", "synthesis", "synopsys", "pragma", "translate_off",
            "translate_on", "coverage", "cadence", "ambit", "xilinx", "altera")
DIRECTIVE = re.compile(r"^\s*(" + "|".join(PREFIXES) + r")(?:\s+[A-Za-z_]|\s*$)", re.I)
WAIVER = re.compile(r"^\s*verilator\s+(lint_off|lint_on)\s+([A-Z][A-Z0-9_]*)\s*$")
SCOPES = ("sim_only", "any")


def setup_error(msg):
    print(f"check_pragmas: SETUP ERROR: {msg}")
    sys.exit(2)


def comments(text):
    """Yield (line, body) for every comment, body without its delimiters."""
    i, n, line = 0, len(text), 1
    while i < n:
        if text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            yield line, text[i + 2:j]
            i = j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            end = n if j < 0 else j
            yield line, text[i + 2:end]
            line += text.count("\n", i, end)
            i = n if j < 0 else j + 2
        elif text[i] == '"':
            j = i + 1
            while j < n and text[j] not in '"\n':
                j += 2 if text[j] == "\\" else 1
            i = j + 1
        else:
            if text[i] == "\n":
                line += 1
            i += 1


def load_gen_cov_vlt():
    spec = importlib.util.spec_from_file_location("gen_cov_vlt", REPO / "tools/gen_cov_vlt.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def read_allowlist():
    if not ALLOWLIST.is_file():
        setup_error(f"{ALLOWLIST.relative_to(REPO)} not found")
    rows = {}
    for ln, raw in enumerate(ALLOWLIST.read_text().splitlines(), 1):
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        f = raw.split("\t")
        if f[0] == "file":
            continue                                   # header
        if len(f) != 5:
            setup_error(f"allowlist line {ln}: {len(f)} tab-separated fields, want 5")
        path, name, pairs, scope, reason = (x.strip() for x in f)
        if not re.fullmatch(r"[1-9][0-9]*", pairs):
            setup_error(f"allowlist line {ln}: pairs '{pairs}' is not a positive integer")
        if scope not in SCOPES:
            setup_error(f"allowlist line {ln}: scope '{scope}' not in {SCOPES}")
        if not reason:
            setup_error(f"allowlist line {ln}: empty reason")
        if (path, name) in rows:
            setup_error(f"allowlist line {ln}: duplicate entry {path} {name}")
        rows[(path, name)] = (int(pairs), scope, ln)
    if not rows:
        setup_error("allowlist has no entries")
    return rows


def main():
    allow = read_allowlist()
    files = sorted(p for p in (REPO / "rtl").rglob("*") if p.suffix in EXTS and p.is_file())
    if not files:
        setup_error("no RTL files found under rtl/")
    gcv = load_gen_cov_vlt()

    bad = []
    n_comments = n_directives = 0
    seen = {}                                   # (file, NAME) -> [(kind, line)]
    for p in files:
        rel = str(p.relative_to(REPO))
        text = p.read_text()
        for line, body in comments(text):
            n_comments += 1
            if not DIRECTIVE.match(body):
                continue
            n_directives += 1
            m = WAIVER.match(body)
            shown = " ".join(body.split())
            if not m:
                bad.append(f"{rel}:{line}: forbidden directive in comment: '{shown}'")
                continue
            seen.setdefault((rel, m.group(2)), []).append((m.group(1), line))

    waivers = 0
    for (rel, name), events in sorted(seen.items()):
        kinds = [k for k, _ in events]
        pairs = len(kinds) // 2
        if kinds != ["lint_off", "lint_on"] * pairs or len(kinds) % 2:
            bad.append(f"{rel}: {name} off/on sequence is unbalanced or out of order: "
                       + ", ".join(f"{k}@{ln}" for k, ln in events))
            continue
        if (rel, name) not in allow:
            bad.append(f"{rel}: lint waiver {name} ({pairs} pair(s), lines "
                       + ", ".join(str(ln) for _, ln in events)
                       + ") is not in ci/pragma_allowlist.tsv")
            continue
        want, scope, aln = allow[(rel, name)]
        if pairs != want:
            bad.append(f"{rel}: {name} has {pairs} pair(s), allowlist line {aln} says {want}")
            continue
        if scope == "sim_only":
            try:
                sim = set(gcv.sim_only_lines((REPO / rel).read_text(), rel))
            except gcv.Refuse as e:
                bad.append(f"{rel}: {name}: cannot evaluate sim_only scope: {e}")
                continue
            for k in range(pairs):
                a, b = events[2 * k][1], events[2 * k + 1][1]
                outside = [ln for ln in range(a, b + 1) if ln not in sim]
                if outside:
                    bad.append(f"{rel}: {name} waiver lines {a}-{b} are scoped sim_only but "
                               f"{len(outside)} line(s) are compiled in synthesis, first {outside[0]}")
        waivers += pairs
        print(f"  waiver  {rel:<24} {name:<14} {pairs} pair(s)  scope {scope}")

    for (rel, name), (_, _, aln) in sorted(allow.items()):
        if (rel, name) not in seen:
            bad.append(f"allowlist line {aln}: {rel} {name} is STALE -- no such waiver in the RTL")

    print(f"check_pragmas: {len(files)} files, {n_comments} comments, "
          f"{n_directives} directive(s), {waivers} allowlisted waiver pair(s)")
    if bad:
        for b in bad:
            print(f"  FAIL  {b}")
        print(f"check_pragmas: FAIL ({len(bad)} violation(s))")
        sys.exit(1)
    print("check_pragmas: PASS")


if __name__ == "__main__":
    main()
