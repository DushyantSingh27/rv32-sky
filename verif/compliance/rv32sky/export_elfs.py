#!/usr/bin/env python3
"""
export_elfs.py -- copy the ACT4 ELF set out of a riscv-arch-test work tree into
verif/compliance/rv32sky/elfs/ and write MANIFEST.sha256 beside it.

Run AFTER run_compliance.sh has regenerated and passed the set. CI runs the
committed copies (ci/check_elfs.py verifies them); regeneration stays on a
machine with the ACT4 framework and the toolchain named in test_config.yaml.

The manifest records, for reproduction rather than enforcement:
  riscv-arch-test commit and its count of local changes, the compiler and
  reference model --version lines (paths read from test_config.yaml), and the
  export time.
and, for enforcement by ci/check_elfs.py:
  every ELF's sha256, EXPECT_TOTAL and EXCLUDE from run_compliance.sh, and the
  sha256 of each ACT4 configuration file in this directory.

Usage:  python3 verif/compliance/rv32sky/export_elfs.py [--replace]
  env:  ACT4  riscv-arch-test checkout (default ~/src/riscv-arch-test)
Exit:   0 exported; 2 refused (nothing written unless stated).
"""

import datetime
import hashlib
import os
import pathlib
import re
import shutil
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parent.parent.parent
ELFDIR = HERE / "elfs"
MANIFEST = ELFDIR / "MANIFEST.sha256"
CONFIGS = ["link.ld", "rv32sky.yaml", "test_config.yaml", "rvmodel_macros.h", "sail.json"]


def refuse(msg):
    print(f"export_elfs: REFUSED: {msg}")
    sys.exit(2)


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def first_line(cmd):
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.TimeoutExpired) as e:
        refuse(f"cannot run {cmd[0]}: {e}")
    out = (r.stdout or r.stderr).strip().splitlines()
    if r.returncode != 0 or not out:
        refuse(f"{' '.join(cmd)} exited {r.returncode} with no version line")
    return out[0].strip()


def yaml_value(text, key):
    vals = re.findall(rf"^{key}:\s*(\S+)\s*$", text, re.M)
    if len(vals) != 1:
        refuse(f"test_config.yaml: found {len(vals)} '{key}' entries, want 1")
    return vals[0]


def main():
    replace = "--replace" in sys.argv[1:]
    act4 = pathlib.Path(os.environ.get("ACT4", str(pathlib.Path.home() / "src/riscv-arch-test")))
    src = act4 / "work/rv32sky/elfs"

    runc = (HERE / "run_compliance.sh").read_text()
    tot = re.findall(r"^EXPECT_TOTAL=([0-9]+)$", runc, re.M)
    exc = re.findall(r'^EXCLUDE="([^"]*)"$', runc, re.M)
    if len(tot) != 1 or len(exc) != 1:
        refuse("run_compliance.sh: want exactly one EXPECT_TOTAL and one EXCLUDE")
    expect_total, exclude = int(tot[0]), exc[0]

    elfs = sorted(p for p in src.rglob("*.elf") if p.is_file()) if src.is_dir() else []
    if len(elfs) != expect_total:
        refuse(f"found {len(elfs)} ELFs under {src}, run_compliance.sh expects {expect_total}. "
               "Run run_compliance.sh first.")

    if ELFDIR.exists() and any(ELFDIR.iterdir()):
        if not replace:
            refuse(f"{ELFDIR.relative_to(REPO)} is not empty; pass --replace to overwrite it")
        shutil.rmtree(ELFDIR)
    ELFDIR.mkdir(parents=True, exist_ok=True)

    tc = (HERE / "test_config.yaml").read_text()
    compiler = yaml_value(tc, "compiler_exe")
    ref_model = yaml_value(tc, "ref_model_exe")
    comp_v = first_line([compiler, "--version"])
    ref_v = first_line([ref_model, "--version"])
    commit = subprocess.run(["git", "-C", str(act4), "rev-parse", "HEAD"],
                            capture_output=True, text=True).stdout.strip()
    if not re.fullmatch(r"[0-9a-f]{40}", commit):
        refuse(f"cannot read the riscv-arch-test commit in {act4}")
    dirty = len(subprocess.run(["git", "-C", str(act4), "status", "--porcelain"],
                               capture_output=True, text=True).stdout.splitlines())

    lines = []
    for p in elfs:
        rel = p.relative_to(src)
        dst = ELFDIR / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(p, dst)
        dst.chmod(0o644)
        h = sha256(dst)
        if h != sha256(p):
            refuse(f"copy of {rel} does not match its source")
        lines.append(f"{h}  {rel}")

    now = datetime.datetime.now().astimezone().isoformat(timespec="seconds")
    head = [
        "# ACT4 ELF set for RV32-SKY. GENERATED by verif/compliance/rv32sky/export_elfs.py.",
        "# Do not edit. Verified by ci/check_elfs.py in L0. docs/results/0030.",
        f"# exported: {now}",
        f"# riscv_arch_test: {commit} ({dirty} local change(s) in the checkout)",
        f"# compiler: {comp_v} ({compiler})",
        f"# ref_model: {ref_v} ({ref_model})",
        f"# exclude: {exclude}",
        f"# expect_total: {expect_total}",
    ]
    for c in CONFIGS:
        p = HERE / c
        if not p.is_file():
            refuse(f"ACT4 config {c} not found in {HERE}")
        head.append(f"# config {sha256(p)} {p.relative_to(REPO)}")
    MANIFEST.write_text("\n".join(head + lines) + "\n")

    mt = [p.stat().st_mtime for p in elfs]
    fmt = lambda t: datetime.datetime.fromtimestamp(t).astimezone().isoformat(timespec="seconds")
    print(f"export_elfs: {len(lines)} ELF(s) -> {ELFDIR.relative_to(REPO)}, "
          f"{sum((ELFDIR / l.split('  ', 1)[1]).stat().st_size for l in lines)} bytes")
    print(f"  source ELF mtimes  {fmt(min(mt))} .. {fmt(max(mt))}")
    for c in CONFIGS:
        print(f"  config mtime       {fmt((HERE / c).stat().st_mtime)}  {c}")
    print("\n".join("  " + h for h in head[2:6]))


if __name__ == "__main__":
    main()
