#!/usr/bin/env bash
# Whole-core properties: imem_addr[1:0] == 0 and !mem_misaligned_o.
#
#   init_zero / init_one   bmc 3    slang honours initial values   PASS / FAIL
#   pc_bmc                 bmc 20   PC alignment, bounded           PASS   (gate)
#   pc_prove               prove 20 PC alignment, unbounded         RECORDED, not gated
#                                   (predicted not PASS: the induction start
#                                   state may hold mtvec_q[1]=1; see 0028)
#   mis_bmc                bmc 20   no misaligned access in MEM     PASS   (gate)
#   mis_prove              prove 20 the same, unbounded             PASS   (gate)
#   cover                  cover 20 -D RISCV_FORMAL: misaligned JAL, JALR, LW
#                                   and SW trap and retire; mret retires   PASS (gate)
#   P1-P3 vs pc_bmc, M1-M3 vs mis_bmc: one trap or mask removed, applied to a
#                                   SCRATCH COPY of the RTL           FAIL each (gate)
#
# The .sby files are GENERATED here from rtl/files.f, so the RTL list exists
# once. Only status PASS counts as a pass (verif/formal/controls). Every job
# runs under a 30-minute cap; a job that hits it is reported, not retried.
#
# OSS CAD Suite shell. Usage: run_core_props.sh [workdir]
# Exit 0 only if every gate holds. Last line: CORE PROPS: ...
set -u -o pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../../.." && pwd)"
WORK="${1:-$HOME/scratch/formal_core_props}"
CAP=1800
GATES=(); BAD=0
rec()  { GATES+=("$*"); echo ">>> $*"; }
gate() { if [ "$1" = "$2" ]; then rec "PASS  $3: $1"; else rec "FAIL  $3: got $1, want $2"; BAD=$((BAD+1)); fi; }

mapfile -t RTL < <(sed -e 's/#.*//' -e 's/[[:space:]]*$//' -e '/^$/d' "$REPO/rtl/files.f")
[ "${#RTL[@]}" -gt 0 ] || { echo "STOP: rtl/files.f is empty"; exit 1; }
for f in "${RTL[@]}"; do [ -f "$REPO/$f" ] || { echo "STOP: $f (rtl/files.f) missing"; exit 1; }; done

rm -rf "$WORK"; mkdir -p "$WORK"
echo "=== tools"; command -v sby yosys yosys-smtbmc boolector timeout; yosys -V
git -C "$REPO" log --oneline -1
echo "=== RTL, from rtl/files.f (${#RTL[@]} files)"; printf '  %s\n' "${RTL[@]}"

# stage <dir> : RTL (flattened) + the two .sv files of this directory
stage() {
  rm -rf "$WORK/$1"; mkdir -p "$WORK/$1"
  for f in "${RTL[@]}"; do cp "$REPO/$f" "$WORK/$1/"; done
  cp "$HERE/core_props.sv" "$HERE/init_ctl.sv" "$WORK/$1/"
}
# sbyfile <dir> <job> <mode> <depth> <top> <defines> <files...>
sbyfile() {
  local dir="$1" job="$2" mode="$3" depth="$4" top="$5" defs="$6"; shift 6
  {
    echo "# GENERATED by run_core_props.sh - not committed."
    echo "[options]"; echo "mode $mode"; echo "depth $depth"; echo
    echo "[engines]"; echo "smtbmc boolector"; echo
    echo "[script]"; echo "plugin -i slang"
    echo "read_slang --std 1800-2017 $defs --top $top $*"
    echo "prep -top $top"; echo
    echo "[files]"; printf '%s\n' "$@"
  } > "$WORK/$dir/$job.sby"
}
# run <dir> <job> -> ST (first word of status), T (seconds)
run() {
  local t0=$SECONDS
  echo; echo "---------- $1/$2"; cat "$WORK/$1/$2.sby"
  ( cd "$WORK/$1" && timeout "$CAP" sby "$2.sby" ) > "$WORK/$1_$2.log" 2>&1; local rc=$?
  cat "$WORK/$1_$2.log"
  T=$((SECONDS - t0))
  if [ "$rc" = 124 ]; then ST=TIMEOUT
  else ST="$(cat "$WORK/$1/$2/status" 2>/dev/null || echo NONE)"; fi
  echo "--- $1/$2: sby exit $rc, status '$ST', ${T} s"
  ST="${ST%% *}"
}
line_of() { grep -n "// $1\$" "$HERE/core_props.sv" | cut -d: -f1; }
failed_on() {   # <dir> <job> <tag>: the counterexample names that assertion
  grep -q "Assert failed in core_props: core_props.sv:$(line_of "$3")\." "$WORK/$1_$2.log"
}

CORE=()
for f in "${RTL[@]}"; do CORE+=("$(basename "$f")"); done
CORE+=(core_props.sv)

echo; echo "==================== CONTROLS: initial values"
stage ctl
sbyfile ctl init_zero bmc 3 init_zero "" init_ctl.sv
sbyfile ctl init_one  bmc 3 init_one  "" init_ctl.sv
run ctl init_zero; gate "$ST" PASS "init_zero (initial value honoured)"
run ctl init_one;  gate "$ST" FAIL "init_one (assertion live)"
if [ "$BAD" -gt 0 ]; then
  echo "STOP: the reset in core_props.sv rests on initial values; nothing after this would mean anything"
  printf '%s\n' "${GATES[@]}"; exit 1
fi

echo; echo "==================== COMMITTED RTL"
stage base
sbyfile base pc_bmc    bmc   20 core_props "-D PROP_PC"      "${CORE[@]}"
sbyfile base pc_prove  prove 20 core_props "-D PROP_PC"      "${CORE[@]}"
sbyfile base mis_bmc   bmc   20 core_props "-D PROP_MIS"     "${CORE[@]}"
sbyfile base mis_prove prove 20 core_props "-D PROP_MIS"     "${CORE[@]}"
sbyfile base cover     cover 20 core_props "-D RISCV_FORMAL" "${CORE[@]}"
run base pc_bmc;    gate "$ST" PASS "pc_bmc (bounded, depth 20)"
run base pc_prove;  rec "READ  pc_prove: status $ST, ${T} s (predicted not PASS; recorded, not gated)"
run base mis_bmc;   gate "$ST" PASS "mis_bmc (bounded, depth 20)"
run base mis_prove; gate "$ST" PASS "mis_prove (unbounded)"
run base cover;     gate "$ST" PASS "cover (all five reached)"
for c in C_JAL C_JALR C_LW C_SW C_MRET; do
  grep -q "Reached cover statement .* core_props.sv:$(line_of "$c")\." "$WORK/base_cover.log" \
    && rec "PASS  cover $c reached" || { rec "FAIL  cover $c not reported reached"; BAD=$((BAD+1)); }
done

# mutant <id> <job> <tag> <file> <old> <new>
mutant() {
  local id="$1" job="$2" tag="$3" file="$4"
  echo; echo "==================== MUTANT $id ($file) vs $job"
  stage "$id"
  if ! python3 - "$WORK/$id/$(basename "$file")" "$5" "$6" <<'PY'
import sys
f, old, new = sys.argv[1:4]
s = open(f).read()
assert s.count(old) == 1, f"anchor occurs {s.count(old)} times"
open(f, "w").write(s.replace(old, new))
PY
  then rec "FAIL  $id: mutation edit did not apply"; BAD=$((BAD+1)); return; fi
  diff "$REPO/$file" "$WORK/$id/$(basename "$file")"
  local defs="-D PROP_PC"; [ "$tag" = A_MIS ] && defs="-D PROP_MIS"
  sbyfile "$id" "$job" bmc 20 core_props "$defs" "${CORE[@]}"
  run "$id" "$job"
  if [ "$ST" = FAIL ] && failed_on "$id" "$job" "$tag"; then rec "PASS  $id killed on $tag, ${T} s"
  else rec "FAIL  $id SURVIVED or failed elsewhere: status $ST"; BAD=$((BAD+1)); fi
}
C=rtl/core/rv32_core.sv; R=rtl/core/csr.sv
mutant P1 pc_bmc  A_PC  $C "if (ex_taken_target_valid && (ex_taken_target[1] != 1'b0)) begin" "if (1'b0) begin"
mutant P2 pc_bmc  A_PC  $R "CSR_MTVEC:     mtvec_q    <= {wval[XLEN-1:2], 2'b00};" "CSR_MTVEC:     mtvec_q    <= wval;"
mutant P3 pc_bmc  A_PC  $R "CSR_MEPC:      mepc_q     <= {wval[XLEN-1:MEPC_LSB_ZEROS], {MEPC_LSB_ZEROS{1'b0}}};" "CSR_MEPC:      mepc_q     <= wval;"
mutant M1 mis_bmc A_MIS $C "end else if (id_ex_q.ctrl.mem_write && ex_ls_misaligned) begin" "end else if (1'b0) begin"
mutant M2 mis_bmc A_MIS $C "end else if (id_ex_q.ctrl.mem_read && ex_ls_misaligned) begin" "end else if (1'b0) begin"
mutant M3 mis_bmc A_MIS $C "ex_mem_ctrl_d.mem_read  = 1'b0;" "ex_mem_ctrl_d.mem_read  = id_ex_q.ctrl.mem_read;"

echo; echo "==================== SUMMARY"
printf '%s\n' "${GATES[@]}"
if [ "$BAD" = 0 ]; then
  echo "CORE PROPS: all gates hold"
  exit 0
fi
echo "CORE PROPS: $BAD gate(s) failed"
exit 1
